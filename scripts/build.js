// Builds a single executable with the server and the whole UI inside.
//
//   bun scripts/build.js                           -> dist/codriver      (the system you build on)
//   bun scripts/build.js --target=bun-windows-x64  -> dist/codriver.exe
//
// Files from public/ are embedded via a generated module, src/assets.gen.js
// (import ... with { type: 'file' }), which the server reads instead of the disk.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dir, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const target = process.argv.find((a) => a.startsWith('--target='))?.split('=')[1];
const windows = target ? target.includes('windows') : process.platform === 'win32';
const outfile = path.join(root, 'dist', windows ? 'codriver.exe' : 'codriver');

// 1. list of UI files
const publicDir = path.join(root, 'public');
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else files.push(p);
  }
})(publicDir);

// 2. a copy of the UI (the server imports public/lib/qr.js as a module, so we embed a copy
//    to keep the bundler from treating one file as both code and asset) + the embedding module
const copyDir = path.join(root, 'dist', '.assets');
fs.rmSync(copyDir, { recursive: true, force: true });
fs.cpSync(publicDir, copyDir, { recursive: true });
const genPath = path.join(root, 'src', 'assets.gen.js');
const lines = ['// Generated by scripts/build.js – do not edit, do not commit.'];
const entries = [];
files.forEach((f, i) => {
  const rel = '/' + path.relative(publicDir, f).split(path.sep).join('/');
  const imp = path.relative(path.dirname(genPath), path.join(copyDir, path.relative(publicDir, f))).split(path.sep).join('/');
  lines.push(`import a${i} from '${imp.startsWith('.') ? imp : './' + imp}' with { type: 'file' };`);
  entries.push(`  ${JSON.stringify(rel)}: a${i},`);
});
lines.push('export default {', ...entries, '};', '');
fs.writeFileSync(genPath, lines.join('\n'));

// 3. compile
fs.mkdirSync(path.dirname(outfile), { recursive: true });
try {
  const result = await Bun.build({
    entrypoints: [path.join(root, 'src', 'main.js')],
    compile: target ? { target, outfile } : { outfile },
    define: { CODRIVER_VERSION: JSON.stringify(pkg.version) },
    minify: true,
  });
  if (!result.success) {
    for (const log of result.logs) console.error(log);
    process.exit(1);
  }
  const size = (fs.statSync(outfile).size / 1e6).toFixed(0);
  console.log(`codriver ${pkg.version}: ${path.relative(root, outfile)} (${size} MB, ${files.length} UI files inside)`);
} finally {
  fs.rmSync(genPath, { force: true });
  fs.rmSync(copyDir, { recursive: true, force: true });
}
